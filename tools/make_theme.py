#!/usr/bin/env python3
"""Composes and synthesizes the tidalfolio signature theme ("Tidal Fable") from scratch.

Everything is generated by this script (no samples, no third-party audio), so the theme is original
and owned by the channel. Output goes to assets/music/theme/: intro.wav, loop.wav, outro.wav.

  python tools/make_theme.py            # render all three
  python tools/make_theme.py --seed 3   # a different "take" (small timing/velocity variations, same tune)

Musical design: 70 BPM, A minor, progression Am - F - C - G (a gentle rolling tide), a four-note piano-like
motif that returns every two bars, harp-like arpeggios, a wordless choir pad and a low drone. No drums.
The outro resolves to A major (a "picardy" ending: bittersweet to hopeful).
"""
import argparse
import wave
from pathlib import Path

import numpy as np
from scipy.signal import butter, fftconvolve, lfilter

SR = 44100
BPM = 70
BEAT = 60.0 / BPM
BAR = 4 * BEAT
OUT = Path(__file__).resolve().parent.parent / "assets" / "music" / "theme"


def hz(midi):
    return 440.0 * 2 ** ((midi - 69) / 12)


NOTE = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}


def m(name):          # "A4" -> midi number
    return 12 * (int(name[-1]) + 1) + NOTE[name[0]] + (1 if "#" in name else 0)


# ------------------------------------------------------------------ instruments
def lp(x, fc, order=2):
    b, a = butter(order, fc / (SR / 2), "low")
    return lfilter(b, a, x)


def pluck(freq, dur, vel=0.8, bright=0.5, rng=None):
    """Karplus-Strong string with a soft, piano/harp-like decay."""
    n = int(SR * dur)
    period = max(2, int(round(SR / freq)))
    buf = (rng.uniform(-1, 1, period) * np.hanning(period) ** 0.3) if rng is not None else np.random.uniform(-1, 1, period)
    buf = lp(buf, 6000 * bright + 1500)
    out = np.empty(n)
    damp = 0.9975 - 0.0006 * (freq / 440.0)
    for i in range(n):
        j = i % period
        out[i] = buf[j]
        buf[j] = damp * 0.5 * (buf[j] + buf[(j + 1) % period])
    env = np.exp(-np.arange(n) / (SR * dur * 0.55))
    return out * env * vel


def piano(freq, dur, vel=0.8, rng=None):
    """Plucked string body plus two soft partials and a short felt-hammer thump."""
    body = pluck(freq, dur, vel, 0.55, rng)
    t = np.arange(len(body)) / SR
    partial = 0.25 * np.sin(2 * np.pi * freq * 2 * t) * np.exp(-t * 3.0) + 0.12 * np.sin(2 * np.pi * freq * 3 * t) * np.exp(-t * 5.0)
    thump = np.sin(2 * np.pi * freq * t) * np.exp(-t * 40) * 0.25
    x = body + vel * (partial + thump)
    return lp(x, 4200)


def harp(freq, dur, vel=0.5, rng=None):
    return lp(pluck(freq, dur, vel, 0.8, rng), 7000)


def pad(freqs, dur, vel=0.5, voice=False):
    """Slow-attack pad: detuned saw-ish oscillators, low-passed; with voice=True add vowel-like formants
    for a wordless 'ooh/aah' choir feel."""
    n = int(SR * dur)
    t = np.arange(n) / SR
    mix = np.zeros(n)
    for f in freqs:
        for det in (-0.07, 0.0, 0.07):                      # gentle chorus
            ph = 2 * np.pi * f * (1 + det / 100) * t
            osc = sum(np.sin(h * ph) / h for h in range(1, 7))
            mix += osc * (1 + 0.15 * np.sin(2 * np.pi * (0.18 + det) * t))   # slow breathing
    mix /= max(1e-9, np.max(np.abs(mix)))
    if voice:
        formants = [(450, 90, 1.0), (850, 110, 0.5), (2400, 200, 0.18)]       # an 'oh/ah' vowel
        v = np.zeros(n)
        for fc, bw, g in formants:
            b, a = butter(2, [(fc - bw) / (SR / 2), (fc + bw) / (SR / 2)], "band")
            v += g * lfilter(b, a, mix)
        mix = 0.55 * mix + 1.6 * v
        mix = lp(mix, 3500)
    else:
        mix = lp(mix, 1800)
    atk, rel = min(dur * 0.45, 1.6), min(dur * 0.45, 2.0)
    env = np.minimum(1, t / atk) * np.minimum(1, (dur - t) / rel)
    return mix * env * vel / max(1e-9, np.max(np.abs(mix)))


def drone(freq, dur, vel=0.4):
    n = int(SR * dur)
    t = np.arange(n) / SR
    x = np.sin(2 * np.pi * freq * t) + 0.5 * np.sin(2 * np.pi * freq * 2.003 * t) + 0.25 * np.sin(2 * np.pi * freq * 3 * t)
    x = lp(x, 400)
    env = np.minimum(1, t / 3.0) * np.minimum(1, (dur - t) / 3.0)
    return x * env * vel / np.max(np.abs(x))


def reverb(x, secs=4.5, wet=0.38, rng=None):
    """Cathedral-ish room: exponentially decaying, darkened noise as an impulse response."""
    rng = rng or np.random.default_rng(1)
    n = int(SR * secs)
    ir = rng.normal(0, 1, n) * np.exp(-np.arange(n) / (SR * secs * 0.28))
    ir = lp(ir, 5000)
    ir[: int(SR * 0.02)] *= np.linspace(0, 1, int(SR * 0.02))
    ir /= np.sqrt(np.sum(ir ** 2))
    stereo = np.zeros((len(x) + n - 1, 2))
    for ch in range(2):                                       # slightly different IR per ear = width
        ir_c = np.roll(ir, ch * 97) if ch else ir
        stereo[:, ch] = fftconvolve(x, ir_c)
    dry = np.zeros_like(stereo)
    dry[: len(x), 0] = x
    dry[: len(x), 1] = x
    return (1 - wet) * dry + wet * stereo * 2.2


# ------------------------------------------------------------------ composition
# chord roots (bass) and chord tones per bar; progression Am - F - C - G
PROG = [
    ("A2", ["A3", "C4", "E4"]),
    ("F2", ["F3", "A3", "C4"]),
    ("C3", ["C4", "E4", "G4"]),
    ("G2", ["G3", "B3", "D4"]),
]
# the signature motif (beat positions within a 2-bar phrase, note, length in beats)
MOTIF = [(0.0, "E5", 1.5), (1.5, "A5", 1.0), (2.5, "G5", 1.0), (3.5, "E5", 3.0)]
ARP = [0, 1, 2, 1]        # chord-tone order for the harp arpeggio


def place(track, sig, t):
    s = int(t * SR)
    if s < 0:
        return
    end = min(len(track), s + len(sig))
    track[s:end] += sig[: end - s]


def render(bars, kind="loop", seed=1):
    """kind: 'loop' (main body), 'intro' (motif + swell) or 'outro' (motif resolving to A major)."""
    rng = np.random.default_rng(seed)
    total = bars * BAR + 0.5
    n = int(SR * total)
    mel, harpt, padt, bass = np.zeros(n), np.zeros(n), np.zeros(n), np.zeros(n)

    for b in range(bars):
        t0 = b * BAR
        root, tones = PROG[b % 4]
        if kind == "outro" and b == bars - 1:                # last bar: A major (C# instead of C)
            root, tones = "A2", ["A3", "C#4", "E4"]
        full = kind != "intro" or b >= bars - 1
        if kind == "loop" or kind == "outro":
            place(padt, pad([hz(m(x)) for x in tones] + [hz(m(tones[0]) + 12)], BAR + 1.2, 0.55, voice=(b // 2) % 2 == 1), t0)
            place(bass, drone(hz(m(root)), BAR + 0.5, 0.5), t0)
        else:                                                # intro: pad swells under the motif
            place(padt, pad([hz(m(x)) for x in tones], BAR + 1.0, 0.45, voice=False), t0)
        if kind == "loop" or (kind == "outro" and b < bars - 1):
            for i, step in enumerate(ARP * 2):               # eighth-note harp arpeggio
                note = hz(m(tones[step]) + 12)
                place(harpt, harp(note, 2.6, 0.38 + 0.08 * (i % 2), rng), t0 + i * BEAT / 2 + rng.normal(0, 0.004))

    phrases = range(0, bars, 2)
    for p in phrases:
        if kind == "loop" and p % 4 == 2 and p % 8 == 2:
            continue                                         # let the tune breathe now and then
        for beat, nm, ln in MOTIF:
            note = m(nm)
            if kind == "outro" and nm == "G5":
                note = m("E5")                               # outro: settle on E5, the fifth of the final A chord
            place(mel, piano(hz(note), ln * BEAT * 2.2, 0.85, rng), p * BAR + beat * BEAT + rng.normal(0, 0.006))

    mix = 1.0 * mel + 0.8 * harpt + 0.9 * padt + 0.7 * bass
    mix = reverb(mix, 4.5, 0.40, rng)
    mix = mix[: int(SR * (bars * BAR + (3.5 if kind == "outro" else 0.2)))]
    if kind == "loop":                                       # make it loop-safe: fold the tail back onto the start
        tail = mix[int(SR * bars * BAR):]
        mix = mix[: int(SR * bars * BAR)]
        mix[: len(tail)] += tail[: len(mix)]
    fade = int(SR * (2.0 if kind == "outro" else 0.01))
    if kind == "outro":
        mix[-fade:] *= np.linspace(1, 0, fade)[:, None]
    if kind == "intro":
        mix *= np.minimum(1, np.arange(len(mix)) / (SR * 0.8))[:, None]
    peak = np.max(np.abs(mix))
    return mix / peak * 0.85


def save(path, stereo):
    pcm = (np.clip(stereo, -1, 1) * 32767).astype("<i2")
    with wave.open(str(path), "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--loop-bars", type=int, default=32, help="bars in the main loop (32 bars = ~110 s)")
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    for name, bars in (("intro", 2), ("loop", a.loop_bars), ("outro", 2)):
        audio = render(bars, name, a.seed)
        save(OUT / f"{name}.wav", audio)
        print(f"{name}.wav  {len(audio) / SR:.1f}s")


if __name__ == "__main__":
    main()
